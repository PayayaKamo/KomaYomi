// Electron main process: start the local backend (which also serves the built frontend), then load it in a window.
// Data directories (raw/ data/ exports/) default to the user directory and can be switched with Ctrl+Shift+D;
// when running from source, keep using the project directory.
const { app, BrowserWindow, dialog, ipcMain, shell } = require('electron');
const fs = require('node:fs');
const path = require('node:path');
const { pathToFileURL } = require('node:url');

const PRODUCT_NAME = 'KomaYomi';

// The product is now KomaYomi but keeps the old userData directory (%APPDATA%/manga-memo),
// so existing users don't lose their data-root config. Rename once a migration plan is settled.
app.setName(PRODUCT_NAME);
app.setPath('userData', path.join(app.getPath('appData'), 'manga-memo'));

const ROOT = path.resolve(__dirname, '..');
const IS_DEV_RUN = Boolean(process.defaultApp); // started from source via `electron .`
let server = null;

const configPath = () => path.join(app.getPath('userData'), 'config.json');

function readConfig() {
  try {
    return JSON.parse(fs.readFileSync(configPath(), 'utf8'));
  } catch {
    return {};
  }
}

function writeConfig(cfg) {
  fs.mkdirSync(path.dirname(configPath()), { recursive: true });
  fs.writeFileSync(configPath(), JSON.stringify(cfg, null, 2));
}

function ensureDataRoot(dir) {
  for (const sub of ['raw', 'data', 'exports']) fs.mkdirSync(path.join(dir, sub), { recursive: true });
  return dir;
}

const defaultDataRoot = () => path.join(app.getPath('userData'), 'library');

/** Merge annotations from the old data directory into the new one (excluding the thumbnail cache) so existing notes/panels are not lost. */
function migrateAnnotations(from, to) {
  const parts = ['pages', 'templates', 'presets'];
  let copied = 0;
  for (const part of parts) {
    const src = path.join(from, part);
    if (!fs.existsSync(src)) continue;
    const dst = path.join(to, part);
    fs.mkdirSync(dst, { recursive: true });
    try {
      fs.cpSync(src, dst, { recursive: true, force: false, errorOnExist: false });
      copied += 1;
    } catch (err) {
      console.error(`[komayomi] 迁移 ${part} 失败：`, err);
    }
  }
  return copied;
}

async function pickFolder(win) {
  const res = await dialog.showOpenDialog(win ?? null, {
    title: '选择数据目录（包含 raw / data / exports）',
    properties: ['openDirectory', 'createDirectory'],
  });
  return res.canceled ? null : res.filePaths[0];
}

async function resolveDataRoot() {
  if (process.env.MANGA_DATA_DIR) return ensureDataRoot(path.resolve(process.env.MANGA_DATA_DIR));

  const cfg = readConfig();
  if (cfg.dataRoot && fs.existsSync(cfg.dataRoot)) return ensureDataRoot(cfg.dataRoot);

  // Running from source (npm run desktop): keep the project directory and preserve the old behavior.
  if (IS_DEV_RUN) {
    writeConfig({ dataRoot: ROOT });
    return ensureDataRoot(ROOT);
  }

  const fallback = ensureDataRoot(defaultDataRoot());
  const hasData = fs.existsSync(path.join(fallback, 'raw'));

  if (!hasData) {
    const { response } = await dialog.showMessageBox({
      type: 'question',
      title: '选择数据目录',
      message: 'KomaYomi 需要一个目录来放漫画图片和标注',
      detail:
        `默认目录：${fallback}\n\n` +
        '· 想把图片放在别处（例如已有的项目目录），选「选择已有目录」\n' +
        '· 目录结构为 raw/卷名/语言/页码.jpg，data/ 存标注',
      buttons: ['选择已有目录…', '使用默认目录', '退出'],
      defaultId: 1,
      cancelId: 2,
    });
    if (response === 2) {
      app.quit();
      return null;
    }
    if (response === 0) {
      const dir = await pickFolder();
      if (dir) {
        writeConfig({ dataRoot: dir });
        return ensureDataRoot(dir);
      }
    }
    writeConfig({ dataRoot: fallback });
    // Migrate legacy annotation data found next to the install directory.
    const legacyData = path.join(ROOT, 'data');
    if (fs.existsSync(legacyData)) migrateAnnotations(legacyData, fallback);
  }

  return fallback;
}

async function createWindow() {
  const dataRoot = await resolveDataRoot();
  if (!dataRoot) return;

  // dist-server/app.mjs is generated by `npm run server:build` (bundles server/*.ts and deps).
  const mod = await import(pathToFileURL(path.join(ROOT, 'dist-server', 'app.mjs')).href);
  const wanted = Number(process.env.MANGA_PORT) || 0;
  const started = await mod.startMangaServer(dataRoot, wanted, path.join(ROOT, 'dist'));
  server = started.server;
  console.log(`[komayomi] http://127.0.0.1:${started.port}  data=${dataRoot}`);

  const win = new BrowserWindow({
    width: 1440,
    height: 900,
    minWidth: 960,
    minHeight: 640,
    backgroundColor: '#0c0e12',
    title: PRODUCT_NAME,
    webPreferences: {
      contextIsolation: true,
      nodeIntegration: false,
      sandbox: true,
      preload: path.join(__dirname, 'preload.cjs'),
    },
  });

  win.setMenuBarVisibility(false);
  win.setTitle(`${PRODUCT_NAME} — ${dataRoot}`);

  // External links go to the system browser instead of opening inside the app.
  win.webContents.setWindowOpenHandler(({ url }) => {
    if (/^https?:/i.test(url) && !url.startsWith(`http://127.0.0.1:${started.port}`)) {
      void shell.openExternal(url);
      return { action: 'deny' };
    }
    return { action: 'allow' };
  });

  // Ctrl+Shift+D switches the data directory (effective after restart).
  win.webContents.on('before-input-event', (event, input) => {
    if (input.type === 'keyDown' && input.control && input.shift && input.key.toLowerCase() === 'd') {
      event.preventDefault();
      void (async () => {
        const dir = await pickFolder(win);
        if (!dir) return;
        writeConfig({ ...readConfig(), dataRoot: dir });
        app.relaunch();
        app.exit(0);
      })();
    }
  });

  await win.loadURL(`http://127.0.0.1:${started.port}/`);

  // Smoke test: with MANGA_SMOKE=<ms>, capture a screenshot and quit automatically.
  const smoke = Number(process.env.MANGA_SMOKE);
  if (smoke > 0) {
    setTimeout(async () => {
      try {
        const os = require('node:os');
        const image = await win.webContents.capturePage();
        const out = process.env.MANGA_SMOKE_SHOT || path.join(os.tmpdir(), 'manga-electron-smoke.png');
        fs.writeFileSync(out, image.toPNG());
        console.log(`[komayomi] smoke shot -> ${out}`);
      } catch (err) {
        console.error('[komayomi] 截图失败', err);
      }
      app.quit();
    }, smoke);
  }
}

app
  .whenReady()
  .then(createWindow)
  .catch((err) => {
    console.error('启动失败：', err);
    dialog.showErrorBox('启动失败', String(err));
    app.quit();
  });

// Called from the renderer through preload: pick a local folder (add manga / switch data directory).
ipcMain.handle('pick-folder', async (_event, title) => {
  const res = await dialog.showOpenDialog({
    title: typeof title === 'string' && title ? title : '选择文件夹',
    properties: ['openDirectory', 'createDirectory'],
  });
  return res.canceled ? null : res.filePaths[0];
});

// Pick where a "save as" copy of the library should be written. The renderer never
// writes files itself: it passes the chosen path to the local server.
ipcMain.handle('save-project-file', async (_event, title, defaultName) => {
  const base = typeof defaultName === 'string' && defaultName ? defaultName : 'komayomi-project';
  const res = await dialog.showSaveDialog({
    title: typeof title === 'string' && title ? title : '另存为',
    defaultPath: base.toLowerCase().endsWith('.mnproj') ? base : `${base}.mnproj`,
    filters: [{ name: 'KomaYomi Project', extensions: ['mnproj'] }],
  });
  return res.canceled || !res.filePath ? null : res.filePath;
});

// Pick a .mnproj to open. The renderer only gets the path: the local server reads the
// file and remembers it, so every later save is written back to that exact file.
ipcMain.handle('pick-project-file', async (_event, title) => {
  const res = await dialog.showOpenDialog({
    title: typeof title === 'string' && title ? title : '打开工程文件',
    properties: ['openFile'],
    filters: [
      { name: 'KomaYomi Project', extensions: ['mnproj'] },
      { name: 'Zip archive', extensions: ['zip'] },
    ],
  });
  return res.canceled ? null : res.filePaths[0];
});

app.on('window-all-closed', () => {
  server?.close();
  app.quit();
});
